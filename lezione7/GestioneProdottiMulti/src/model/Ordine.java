package model;

public class Ordine {
	private int id;
	private String nomeOrdine;
	
	public int getId() {
		return id;
	}
	public void setId(int id) {
		this.id = id;
	}
	public String getNomeOrdine() {
		return nomeOrdine;
	}
	public void setNomeOrdine(String nomeOrdine) {
		this.nomeOrdine = nomeOrdine;
	}
	
}
